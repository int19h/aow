"""Merge RTTI, persisted-field tables, and getter-derived names into one layout per class.

Usage: class_layout.py <rtti.txt> <persisted-fields.md> <field-names.md> <out.md> [UnitName]

For every class in the RTTI file (default unit filter: AoWE) the output lists the parent, the instance size,
and one row per known offset: the field name (from getters and setters), the C type seen there, the
persistence call that stores it, and its property id. Inherited rows come from the parent chain so that a
class table is complete on its own. Unknown gaps between known offsets are shown as "?" so that the
remaining work is visible.
"""
import re, sys, collections


def read_rtti(path):
    classes = collections.OrderedDict()
    for line in open(path, encoding='utf-8'):
        m = re.match(r'class (\w+) \((\S+)\) size=(\d+) virtuals=(\d+)', line)
        if m:
            classes[m.group(1)] = dict(parent=m.group(2), size=int(m.group(3)), virtuals=int(m.group(4)))
    return classes


def read_tables(path, unit_filter):
    """Parse the markdown tables written by readwrite_table.py and field_names.py."""
    tables = {}
    cur = None
    for line in open(path, encoding='utf-8'):
        m = re.match(r'## (\w+)\.(T\w+)', line)
        if m:
            cur = m.group(2) if m.group(1) == unit_filter else None
            if cur: tables[cur] = []
            continue
        if cur and line.startswith('| ') and not line.startswith('| id') and not line.startswith('| offset') and not line.startswith('|---'):
            cells = [c.strip() for c in line.strip().strip('|').split('|')]
            tables[cur].append(cells)
    return tables


SIZE_BY_RW = {'rwInteger': 4, 'rwIntegerEx': 4, 'rwString': 4, 'rwStrings': 4, 'rwStringsEx': 4,
              'rwEObject': 4, 'rwCreateEObject': 4, 'rwWord': 2, 'rwWordEx': 2,
              'rwByte': 1, 'rwByteEx': 1, 'rwBool': 1, 'rwShortint': 1, 'rwShortintEx': 1}
SIZE_BY_C = {'byte': 1, 'char': 1, 'undefined1': 1, 'bool': 1, 'short': 2, 'ushort': 2, 'undefined2': 2,
             'int': 4, 'uint': 4, 'undefined4': 4, 'float': 4, 'int *': 4, 'code *': 4, 'undefined4 *': 4,
             'double': 8, 'longlong': 8}


def main():
    rtti_path, pf_path, fn_path, out_path = sys.argv[1:5]
    unit = sys.argv[5] if len(sys.argv) > 5 else 'AoWE'
    classes = read_rtti(rtti_path)
    persisted = read_tables(pf_path, unit)
    named = read_tables(fn_path, unit)

    def own_rows(cls):
        rows = {}
        for cells in persisted.get(cls, []):
            pid, rw, off, size, note = (cells + [''] * 5)[:5]
            if not off.startswith('+$'): continue
            o = int(off[2:], 16)
            r = rows.setdefault(o, {})
            r['rw'] = rw; r['id'] = pid; r['note'] = note
            r['size'] = int(size) if size.isdigit() else SIZE_BY_RW.get(rw, 0)
        for cells in named.get(cls, []):
            off, name, ctype = (cells + [''] * 4)[:3]
            if not off.startswith('+$'): continue
            o = int(off[2:], 16)
            r = rows.setdefault(o, {})
            r['name'] = name; r['ctype'] = ctype
            r.setdefault('size', SIZE_BY_C.get(ctype, 0))
        return rows

    def chain(cls):
        out = []
        while cls in classes:
            out.append(cls)
            cls = classes[cls]['parent']
        return out

    lines = ['# %s class layouts' % unit, '',
             'Generated by tools/class_layout.py from RTTI, ReadWrite tables, and trivial accessors.',
             'Rows marked (inherited) come from a parent class in the same unit. Parents outside the unit',
             '(Engine.TEObject, HSEngine.*) are not expanded; their fields appear as a gap before the first row.', '']
    for cls, info in classes.items():
        if cls not in persisted and cls not in named:
            continue
        rows = {}
        for c in reversed(chain(cls)):
            for o, r in own_rows(c).items():
                merged = dict(rows.get(o, {}))
                merged.update(r)
                merged['from'] = c
                rows[o] = merged
        lines.append('## %s : %s  (size %d, %d virtual methods)' % (cls, info['parent'], info['size'], info['virtuals']))
        lines.append('')
        lines.append('| offset | size | field | c type | persisted as | id | note |')
        lines.append('|---|---|---|---|---|---|---|')
        prev_end = None
        for o in sorted(rows):
            r = rows[o]
            if prev_end is not None and o > prev_end:
                lines.append('| +$%02X | %d | ? | | | | gap |' % (prev_end, o - prev_end))
            inh = '' if r['from'] == cls else ' (%s)' % r['from']
            lines.append('| +$%02X | %s | %s%s | %s | %s | %s | %s |' % (
                o, r.get('size') or '', r.get('name', ''), inh, r.get('ctype', ''), r.get('rw', ''), r.get('id', ''), r.get('note', '')))
            prev_end = o + (r.get('size') or 0)
        if prev_end is not None and prev_end < info['size']:
            lines.append('| +$%02X | %d | ? | | | | gap to end |' % (prev_end, info['size'] - prev_end))
        lines.append('')
    open(out_path, 'w', encoding='utf-8').write('\n'.join(lines))
    print('%d classes -> %s' % (sum(1 for l in lines if l.startswith('## ')), out_path))


main()
